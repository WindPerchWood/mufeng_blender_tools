def pick_default(items, preferred):
    if not items:
        raise ValueError("枚举项为空")
    for ident, _label, _desc in items:
        if ident == str(preferred):
            return ident
    try:
        target = float(preferred)
        return min(items, key=lambda it: abs(float(it[0]) - target))[0]
    except (TypeError, ValueError):
        return items[0][0]


