def bearing_items():
    out = []
    for code in sorted(BALL_BEARINGS, key=lambda c: (len(c), c)):
        d, D, B = BALL_BEARINGS[code]
        out.append((code, code, "d=%g  D=%g  B=%g" % (d, D, B)))
    return out


